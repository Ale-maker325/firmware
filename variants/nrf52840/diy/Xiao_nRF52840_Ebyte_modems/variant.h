/*
 * Схема: D19 → 100–300 Ом → вход модуля реле 3,3 В; 10 кОм от входа к земле (при сбросе, в загрузчике и во
 * время прошивки вывод висит в воздухе — без подтяжки реле может щёлкнуть). Для сервопривода — сигнал ШИМ
 * 3,3 В (питание сервопривода от 5 В, не от 3V3 XIAO); в Meshtastic сервоприводы не поддерживаются.
 * Управление реле по радиосети — модуль Remote Hardware Meshtastic. Он выключен во всём проекте
 * (MESHTASTIC_EXCLUDE_REMOTEHARDWARE=1 в корневом platformio.ini) — включается строкой в platformio.ini
 * этого варианта. Затем на обоих узлах:
 *   meshtastic --set remote_hardware.enabled true --set remote_hardware.allow_undefined_pin_access true
 *   meshtastic --ch-add gpio          (канал «gpio» с одинаковым ключом на обоих узлах — его требует CLI)
 * Включить / выключить реле на удалённом узле:
 *   meshtastic --gpio-wrb 39 1 --dest "!a1b2c3d4"
 *   meshtastic --gpio-wrb 39 0 --dest "!a1b2c3d4"
 * Проверить состояние:  meshtastic --gpio-rd 0x8000000000 --dest "!a1b2c3d4"   (маска бита 39)
 */

