// СХЕМА ПИТАНИЯ (как у варианта ProMicro): батарея 2S → понижающий MP2225 → 5 В на вывод 5V XIAO и на модем.
// Площадки BAT+/BAT- XIAO НЕ подключать: встроенный зарядник BQ25101 (1S, до 100 мА) не используется,
// батарея 2S заряжается своим зарядником с BMS. Поэтому EXT_CHRG_DETECT (P0.17) и делитель платы
// (P0.31 / P0.14) не задаём: без батареи на BAT выход ~CHG зарядника ничего не значит.
// По схеме Seeed (v1.2): BAT+ → 1 МОм → P0.31 (он же вывод D16) → 510 кОм → P0.14. Когда на 5V есть питание,
// BQ25101 держит на пустых площадках BAT ~4,2 В; если P0.14 не в нуле, P0.31 получает больше допустимых 3,6 В
// (Seeed это прямо запрещает). Поэтому variant.cpp держит P0.14 в LOW постоянно (делитель 1,5 МОм: ~3 мкА).
// Площадки BAT+/BAT- и вывод D16 ничем не нагружать. Красный светодиод заряда платы (P0.17, аппаратный)
// без батареи может светиться или мигать — на работу не влияет.
// PROMICRO_DIY_TCXO не задаём по той же причине, что у ProMicro: на VBUS всегда 5 В от MP2225, и прошивка
// считала бы, что всегда подключён USB. «USB» = напряжение батареи выше первой точки OCV_ARRAY + 10 мВ.

/*
 * ----------------------------------------------------------------------------
 * ДЕЛИТЕЛЬ БАТАРЕИ НА D0 (P0.02, вход АЦП AIN0)
 * ----------------------------------------------------------------------------
 * D0 — единственный свободный вход АЦП; внутри XIAO к P0.02 ничего не подключено (схема Seeed v1.2).
 * R1 — от плюса батареи к D0, R2 — от D0 к земле; параллельно R2 — керамика 100 нФ (АЦП nRF52840
 * заряжает свой конденсатор выборки от делителя, 100 нФ делает замер стабильным при сопротивлении
 * делителя ~150 кОм). Напряжение на D0 не должно превышать 3,0 В (опорное АЦП ниже).
 *
 * | Батарея | Макс. вольт | R1 (к плюсу) | R2 (к земле) | Вольт на АЦП | Ток утечки | Рекомендация |
 * | ------- | ----------- | ------------ | ------------ | ------------ | ---------- | ------------ |
 * | 2S LiPo | 8.4 В       | 470 кОм      | 220 кОм      | 2.68 В       | 12.2 мкА   | ОПТИМАЛЬНО   |
 * | 2S LiPo | 8.4 В       | 1 МОм        | 470 кОм      | 2.68 В       | 5.7 мкА    | Микроток     |
 * | 3S LiPo | 12.6 В      | 1 МОм        | 270 кОм      | 2.68 В       | 9.9 мкА    | ОПТИМАЛЬНО   |
 * | 3S LiPo | 12.6 В      | 2.2 МОм      | 680 кОм      | 2.97 В       | 4.4 мкА    | Микроток     |
 * Для других номиналов пересчитать VBAT_DIVIDER_COMP = (R1 + R2) / R2.
 *
 * Калибровка без перепрошивки (разброс резисторов 1–5 %):
 *   1. Замерить мультиметром напряжение батареи: Uреал.
 *   2. Посмотреть напряжение в прошивке (поле "voltage" своего узла):  meshtastic --info
 *   3. Новый множитель = ADC_MULTIPLIER * Uреал / Uпрошивки, например 3.13636 * 8.20 / 8.05 = 3.1948
 *        meshtastic --set power.adc_multiplier_override 3.1948
 *   4. Проверить через ~1 минуту. Вернуть значение из прошивки:  meshtastic --set power.adc_multiplier_override 0
 * ----------------------------------------------------------------------------
 */
