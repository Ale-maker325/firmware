#define PIN_SPI_SCK (32 + 11)  // Линия тактирования шины SPI на выводе P1.11

// Системные привязки линий SPI, используемые ядром связи прошивки
#define LORA_MISO PIN_SPI_MISO
#define LORA_MOSI PIN_SPI_MOSI
#define LORA_SCK PIN_SPI_SCK
#define LORA_CS (32 + 13) // Вывод выбора кристалла трансивера CS на P1.13

