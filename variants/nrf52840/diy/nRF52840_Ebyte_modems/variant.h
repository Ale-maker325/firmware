// Расчет параметров АЦП: диапазон 3.0V при разрешении 12-бит = 3000мВ / 4096
#define VBAT_MV_PER_LSB (0.73242188F)
// Параметры делителя напряжения на плате: резисторы 1.5M и 1M => (1.5M / (1M + 1.5M))
#define VBAT_DIVIDER (0.6F)
// Коэффициент компенсации погрешности делителя напряжения
#define VBAT_DIVIDER_COMP (1.73)
// Итоговый расчет цены деления АЦП в милливольтах с учетом компенсации
#define REAL_VBAT_MV_PER_LSB (VBAT_DIVIDER_COMP * VBAT_MV_PER_LSB)
#undef AREF_VOLTAGE
#define AREF_VOLTAGE 3.0
#define VBAT_AR_INTERNAL AR_INTERNAL_3_0
#define ADC_MULTIPLIER VBAT_DIVIDER_COMP 
#define VBAT_RAW_TO_SCALED(x) (REAL_VBAT_MV_PER_LSB * x)

// Конфигурация аппаратного интерфейса I2C (Шина Wire)
#define WIRE_INTERFACES_COUNT 1
#define PIN_WIRE_SDA (32 + 4) // Линия данных SDA назначена на вывод P1.04
#define PIN_WIRE_SCL (0 + 11) // Линия тактирования SCL назначена на вывод P0.11

// Параметры встроенного системного светодиода
#define PIN_LED1 (0 + 15) // Вывод P0.15 (физически красный светодиод на плате)
#define LED_BUILTIN PIN_LED1
#define LED_BLUE PIN_LED1
#define LED_STATE_ON 1 // Уровень логической единицы включает светодиод

// Конфигурация аппаратной кнопки управления пользовательского интерфейса
#define BUTTON_PIN (32 + 0) // Вывод P1.00

// Конфигурация интерфейса подключения GPS-модуля
#define PIN_GPS_TX (0 + 22) // Вывод P0.22 (Передача данных со стороны МК к GPS)
#define PIN_GPS_RX (0 + 20) // Вывод P0.20 (Прием данных МК от GPS модуля)
#define PIN_GPS_EN (0 + 24) // Вывод P0.24 (Управление ключом питания GPS-модуля)
#define GPS_UBLOX

// Конфигурация аппаратных интерфейсов UART (последовательные порты)
