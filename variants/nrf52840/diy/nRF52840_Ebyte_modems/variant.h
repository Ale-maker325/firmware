// Управление питанием периферии 3.3V (Вывод P0.13 должен оставаться активным для питания LoRa)
#define PIN_3V3_EN (0 + 13) // P0.13

// Конфигурация аналоговых пинов для измерения напряжения батареи
#define BATTERY_PIN (0 + 31) // Вывод P0.31 служит входом АЦП контроля батареи
