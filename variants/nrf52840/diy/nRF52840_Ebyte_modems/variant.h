/*
 * ----------------------------------------------------------------------------
 * СПРАВОЧНАЯ ТАБЛИЦА РЕЗИСТОРНЫХ ДЕЛИТЕЛЕЙ (СОХРАНИТЬ ДЛЯ ПАЙКИ ПЛАТЫ!)
 * ----------------------------------------------------------------------------
 * Как это работает: Напряжение батареи (8.4В или 12.6В) слишком высокое для чипа.
 * Мы ставим два резистора: R1 (от плюса батареи к пину P0.31) и R2 (от пина P0.31 к GND земли).
 * 
 * ВАЖНОЕ ПРАВИЛО ДЛЯ ДЕТЕЙ И ВЗРОСЛЫХ:
 * Параллельно резистору R2 (между пином P0.31 и Землей) ОБЯЗАТЕЛЬНО припаяйте керамический
 * конденсатор на 100 нФ (0.1 мкФ). Он уберет все шумы и сделает измерения идеально точными!
 *
 * | Батарея | Макс. вольт | R1 (к Плюсу) | R2 (к Земле) | Вольт на АЦП | Утечка тока | Рекомендация |
 * | ------- | ----------- | ------------ | ------------ | ------------ | ----------- | ------------ |
 * | 2S LiPo | 8.4 В       | 470 кОм      | 220 кОм      | 2.68 В       | 12.2 мкА    | ОПТИМАЛЬНО   |
 * | 2S LiPo | 8.4 В       | 1 МОм        | 470 кОм      | 2.68 В       | 5.7 мкА     | Микро-ток    |
 * | 2S LiPo | 8.4 В       | 200 кОм      | 100 кОм      | 2.80 В       | 28.0 мкА    | Без кондера  |
 * | 3S LiPo | 12.6 В      | 1 МОм        | 270 кОм      | 2.68 В       | 9.9 мкА     | ОПТИМАЛЬНО   |
 * | 3S LiPo | 12.6 В      | 2.2 МОм      | 680 кОм      | 2.97 В       | 4.4 мкА     | Микро-ток    |
 * | 3S LiPo | 12.6 В      | 330 кОм      | 100 кОм      | 2.93 В       | 29.3 мкА    | Без кондера  |
 * ----------------------------------------------------------------------------
 */

